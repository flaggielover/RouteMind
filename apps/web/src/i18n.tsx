export function detectInitialLocale(
  storage: Pick<Storage, "getItem"> | null = typeof window === "undefined"
    ? null
    : window.localStorage,
  languages: readonly string[] = typeof navigator === "undefined"
    ? []
    : navigator.languages?.length
      ? navigator.languages
      : [navigator.language],
): Locale {
  try {
    const persisted = storage?.getItem(LOCALE_STORAGE_KEY);
    if (isLocale(persisted)) return persisted;
  } catch {
    // Storage can be unavailable in privacy-restricted browser contexts.
  }
  return languages.some((language) => language.toLowerCase().startsWith("zh")) ? "zh-CN" : "en-US";
}

function interpolate(template: string, variables?: Record<string, string | number>): string {
  if (!variables) return template;
  return template.replace(/\{(\w+)\}/g, (_match, key: string) =>
    String(variables[key] ?? `{${key}}`),
  );
}

export interface LocaleContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: string, variables?: Record<string, string | number>) => string;
  formatNumber: (value: number, options?: Intl.NumberFormatOptions) => string;
  formatDateTime: (value: Date | string | number, options?: Intl.DateTimeFormatOptions) => string;
  formatRelative: (value: number, unit: Intl.RelativeTimeFormatUnit) => string;
}

const LocaleContext = createContext<LocaleContextValue | null>(null);

const fallbackLocaleContext: LocaleContextValue = {
  locale: "en-US",
  setLocale: () => undefined,
  t: (key, variables) => interpolate(messages["en-US"][key] ?? key, variables),
  formatNumber: (value, options) => new Intl.NumberFormat("en-US", options).format(value),
  formatDateTime: (value, options) =>
    new Intl.DateTimeFormat("en-US", options).format(new Date(value)),
  formatRelative: (value, unit) =>
    new Intl.RelativeTimeFormat("en-US", { numeric: "auto" }).format(value, unit),
};

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => detectInitialLocale());
  const setLocale = useCallback((nextLocale: Locale) => {
    setLocaleState(nextLocale);
    try {
      window.localStorage.setItem(LOCALE_STORAGE_KEY, nextLocale);
    } catch {
      // Locale state still applies for this session when persistence is blocked.
    }
  }, []);
  const value = useMemo<LocaleContextValue>(
    () => ({
      locale,
      setLocale,
      t: (key, variables) =>
        interpolate(messages[locale][key] ?? messages["en-US"][key] ?? key, variables),
      formatNumber: (valueToFormat, options) =>
        new Intl.NumberFormat(locale, options).format(valueToFormat),
      formatDateTime: (valueToFormat, options) =>
        new Intl.DateTimeFormat(locale, options).format(new Date(valueToFormat)),
      formatRelative: (valueToFormat, unit) =>
        new Intl.RelativeTimeFormat(locale, { numeric: "auto" }).format(valueToFormat, unit),
    }),
    [locale, setLocale],
  );
  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLocale(): LocaleContextValue {
  const value = useContext(LocaleContext);
  return value ?? fallbackLocaleContext;
}
